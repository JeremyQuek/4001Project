"""A short plain-language summary for the team (not for submission).

Every number is read from saved artifacts (results.json, aggregation.json), so the
summary cannot drift from the report. Run after stages 8 and 10.
"""

from common import OUTPUTS, read_json


def pct(value):
    return f'{100 * value:.1f}%'


def points(pair):
    return f'{100 * pair[0]:+.1f} to {100 * pair[1]:+.1f} points'


def table(header, rows):
    lines = ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
    lines += ['| ' + ' | '.join(str(cell) for cell in row) + ' |' for row in rows]
    return '\n'.join(lines)


def main():
    results, extra = read_json(OUTPUTS / 'results.json'), read_json(OUTPUTS / 'aggregation.json')
    test = results['cohorts']['all']
    models, comparisons = test['models'], test['bootstrap']['comparisons']
    detector = extra['detector_used']
    layer = detector.rsplit('hidden', 1)[1]
    methods, routers, rules = extra['methods'], extra['cascade']['routers'], extra['aggregation_rules']['rules']
    errors, consistency, gain = extra['error_types'], extra['consistency'], extra['aggregate_minus_single']

    def auroc(name):
        entry = models[name]
        low, high = entry['auroc_image_bootstrap95']
        return f"{entry['auroc']:.3f} ({low:.3f} to {high:.3f})"

    detection = [['Confidence only, nothing trained', auroc('heuristic_confidence'), '']]
    detection += [[label, auroc(f'lr_all_{key}'), auroc(f'mlp_all_{key}')] for label, key in
                  (('Confidence `[p_yes, confidence]`', 'confidence'), ('Hidden layer 9', 'hidden9'),
                   ('Hidden layer 18', 'hidden18'), ('Hidden layer 36', 'hidden36'))]
    versus_confidence = comparisons[f'{detector}_minus_mlp_all_confidence']

    def at(name, target):
        point = next(p for p in methods[name]['points'] if p['target_coverage'] == target)
        return f"{pct(point['accuracy_on_answered'])} (answers {pct(point['coverage'])})"

    single = methods['single_no_abstention']['points'][0]['accuracy_on_answered']
    aggregated = methods['aggregate']['points'][0]['accuracy_on_answered']
    usage = [['Single query (baseline)', 1, pct(single), 'n/a', 'n/a'],
             ['1. Abstain, using confidence', 1, pct(single), at('abstain_confidence', .8), at('abstain_confidence', .6)],
             [f'1. Abstain, using the layer-{layer} MLP', 1, pct(single), at('abstain_detector', .8),
              at('abstain_detector', .6)],
             ['2. Aggregate the four variants', 4, pct(aggregated), 'n/a', 'n/a'],
             ['3. Aggregate, then abstain on a small margin', 4, pct(aggregated), at('aggregate_abstain_margin', .8),
              at('aggregate_abstain_margin', .6)]]

    mlp_route, confidence_route = routers[detector]['points'], routers['confidence']['points']
    cascade = [[f"{m['mean_vlm_calls']:.1f}", pct(m['target_escalation']), pct(m['random_router_accuracy']),
                pct(c['accuracy']), pct(m['accuracy']),
                pct(m['with_abstention']['accuracy_on_answered']) if 'with_abstention' in m else 'n/a']
               for m, c in zip(mlp_route, confidence_route) if round(m['target_escalation'] * 10) in (0, 2, 4, 5, 7, 10)]
    half, most = mlp_route[5], mlp_route[7]

    def rule_row(entry):
        by_share = {round(p['target_escalation'], 1): p['accuracy'] for p in entry['cascade']}
        return [entry['label'], pct(entry['accuracy']),
                'baseline' if entry['label'].startswith('Confidence only')
                else f"{100 * entry['minus_confidence_rule']:+.1f} ({points(entry['minus_confidence_rule_image_bootstrap95'])})",
                pct(entry['false_yes_rate']), pct(entry['abstention'][0]['accuracy_on_answered']), pct(by_share[0.5])]
    weighted = rules['trust_weighted']

    text = f"""# Visual Genome results: summary for the team

Internal notes, not for submission. Generated by `scripts/11_team_summary.py` from saved
results; full tables are in `outputs/REPORT.md`.

## In short

- The VLM gets {pct(test['unfiltered_vlm_accuracy'])} of spatial Yes/No questions right on the test split.
- A small MLP on the last hidden layer (layer {layer}) detects its wrong answers better than its
  own confidence does (test AUROC {models[detector]['auroc']:.3f} against {models['heuristic_confidence']['auroc']:.3f}).
- Detecting errors only lets us withhold answers. Asking the same fact four ways and averaging
  (aggregation) actually corrects them: {pct(single)} to {pct(aggregated)} on validation.
- The best use of the MLP is as a router: verify only the answers it flags. That reaches the
  full aggregation accuracy with about {most['mean_vlm_calls']:.1f} VLM calls per question in place of 4.
- Feeding the MLP's error probability into the aggregation itself did not clearly help.

## What was run

- Same frozen VLM set-up as the VSR run (Qwen2.5-VL-3B, 4-bit, same prompt).
- Visual Genome, eight spatial predicates, 2,000 relationships. Each relationship becomes four
  statements: the original, its converse (both true), and a swapped and an opposite version
  (both false). That gives 8,000 Yes/No questions, split by image into train, validation and test.
- Detectors are trained to predict "the VLM's answer is wrong" from either the confidence or
  one hidden layer.

## Part 1. Can we detect wrong answers? (test split, the main result)

AUROC with 95% interval. 0.5 is guessing.

{table(['Detector input', 'Logistic regression', 'MLP'], detection)}

- Layer {layer} beats confidence: the MLP is ahead by {versus_confidence['auroc_delta']:+.3f}
  ({versus_confidence['paired_image_bootstrap95'][0]:+.3f} to {versus_confidence['paired_image_bootstrap95'][1]:+.3f}).
- Layers 9 and 18 are worse than confidence.
- These are on Visual Genome. The VSR numbers are on a different dataset, so the two sets of
  AUROCs should not be compared directly.

## Part 2. What can we do with the signal? (validation split, exploratory)

Everything from here on was added after the test evaluation, so it uses validation only
({extra['rows']} questions, {extra['relationships']} relationships). Treat it as exploratory.

{table(['Approach', 'VLM calls per question', 'Accuracy, answering everything', 'Withholding about 20%',
        'Withholding about 40%'], usage)}

- Aggregation gains {100 * gain['accuracy_gain']:+.1f} points ({points(gain['image_bootstrap95'])}).
- Why it works: the VLM is inconsistent. It gets all four versions of a fact right for only
  {pct(consistency['all_four_correct'])} of relationships.
- Hallucination in the strict sense ("Yes" to a false statement) falls from
  {pct(errors['single_false_yes_rate'])} to {pct(errors['aggregate_false_yes_rate'])} with aggregation.

## Part 3. Cascade: verify only the risky answers

Every question gets one call. A router picks the riskiest share; those get three more calls and
the aggregated answer.

{table(['Mean VLM calls', 'Share verified', 'Random router', 'Confidence router', f'Layer-{layer} MLP router',
        'MLP router, then withhold to 80% coverage'], cascade)}

- With half the questions verified ({half['mean_vlm_calls']:.1f} calls), the MLP router gives {pct(half['accuracy'])};
  picking at random gives {pct(half['random_router_accuracy'])}
  (the MLP's gain over random is {points(half['gain_over_random_image_bootstrap95'])}).
- At {most['mean_vlm_calls']:.1f} calls the MLP router has sent {pct(most['single_errors_escalated'])} of the wrong
  single answers for verification and matches always-verify ({pct(most['accuracy'])} against {pct(aggregated)}).

![Cascade accuracy against VLM calls](figure_cascade.png)

## Part 4. Does using the MLP inside the aggregation help?

Here the aggregation of the four calls also uses the MLP's error probability for each call.

- Trust weighting: each call's confidence counts in proportion to how much the MLP trusts it.
- Detector votes: each call's Yes/No answer counts as much as the MLP trusts it; confidence is dropped.
- Both: the average of the two.

{table(['Aggregation rule', 'Accuracy', 'Change against confidence only (95% interval)',
        'Yes to a false statement', 'Withholding about 20%', 'Cascade at 2.5 calls'],
       [rule_row(entry) for entry in rules.values()])}

- No rule is clearly better than plain confidence averaging: every interval includes zero.
  Trust weighting is {100 * weighted['minus_confidence_rule']:+.1f} points, which is within noise.
- Dropping confidence and using only the MLP's votes is the weakest rule.
- These are four fixed rules; picking the best one from this table would be tuning on validation.

## Trade-offs

| Option | Cost | What you get | Main drawback |
|---|---|---|---|
| Single query + MLP | 1 call | Flags likely errors; can withhold them | Cannot fix an answer |
| Cascade with MLP router | about 2.5 to 3 calls | Most or all of the aggregation gain | Needs hidden states and a trained detector |
| Always aggregate | 4 calls | Highest accuracy, no detector needed | Most expensive |

## Caveats

- Parts 2 to 4 are validation-only and were not in the original plan. The MLP was also chosen
  on validation, so its numbers there are slightly optimistic.
- Aggregation needs the question rewritten as a converse, swap and opposite. Here those come
  from an annotated true relationship, so each group of four is balanced by construction.
- Truth labels come from Visual Genome annotations without a geometry check, so some "errors"
  are label noise.
- One model, one prompt, one dataset.

## Files

- `outputs/REPORT.md`: all tables, including breakdowns by predicate and variant.
- `outputs/results.json`: test results, same metric names as the VSR run.
- `outputs/aggregation.json`: everything in parts 2 to 4.
- `ASSUMPTIONS.md`: every decision and why.
"""
    (OUTPUTS / 'TEAM_SUMMARY.md').write_text(text, encoding='utf-8')
    print('saved TEAM_SUMMARY.md')


if __name__ == '__main__':
    main()
