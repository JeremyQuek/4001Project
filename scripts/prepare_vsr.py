"""Download VSR metadata, normalize rows, and create image-disjoint manifests.

No images or VLM outputs are downloaded/generated by this script.
"""
import argparse
import csv
import hashlib
import json
import random
import re
from collections import Counter, defaultdict
from pathlib import Path
from urllib.parse import urlparse
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
REVISION = 'b27a0af0ee1462d2b6b92c8c83e869d9254a241a'
RELATIONS = {'left of', 'right of', 'above', 'below'}


def save_jsonl(path, rows):
    path.write_text(''.join(json.dumps(row, ensure_ascii=False) + '\n' for row in rows), encoding='utf-8')


def describe(rows):
    return {
        'statements': len(rows), 'unique_images': len({r['image_id'] for r in rows}),
        'truth_labels': dict(Counter(str(r['truth_label']) for r in rows)),
        'relations': dict(sorted(Counter(r['relation'] for r in rows).items())),
        'splits': {
            split: {'statements': sum(r['split'] == split for r in rows),
                    'images': len({r['image_id'] for r in rows if r['split'] == split})}
            for split in ('train', 'validation', 'test')
        },
    }


def image_manifest(path, rows):
    images = {}
    for row in rows:
        value = {k: row[k] for k in ('image_id', 'image_path', 'image_url', 'split')}
        if row['image_id'] in images and images[row['image_id']] != value:
            raise ValueError('Conflicting image metadata: ' + row['image_id'])
        images[row['image_id']] = value
    with path.open('w', newline='', encoding='utf-8') as handle:
        writer = csv.DictWriter(handle, fieldnames=['image_id', 'image_path', 'image_url', 'split'])
        writer.writeheader()
        writer.writerows(images[key] for key in sorted(images))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--seed', type=int, default=42)
    parser.add_argument('--download-metadata', action='store_true', help='Fetch missing metadata files at the pinned official revision.')
    args = parser.parse_args()
    raw = ROOT / 'data/vsr/raw'
    processed = ROOT / 'data/vsr/processed'
    raw.mkdir(parents=True, exist_ok=True)
    processed.mkdir(parents=True, exist_ok=True)
    provenance_path = raw / 'sources.json'
    provenance = json.loads(provenance_path.read_text(encoding='utf-8')) if provenance_path.exists() else None
    if provenance is not None and provenance['revision'] != REVISION:
        raise ValueError('Cached revision differs from the pinned preprocessing revision.')
    sources, raw_rows = [], []
    for split in ('train', 'dev', 'test'):
        path = raw / f'{split}.jsonl'
        url = f'https://raw.githubusercontent.com/cambridgeltl/visual-spatial-reasoning/{REVISION}/data/splits/random/{split}.jsonl'
        if not path.exists():
            if not args.download_metadata:
                parser.error(f'Missing {path}; rerun with --download-metadata.')
            with urlopen(url, timeout=60) as response:
                path.write_bytes(response.read())
        content = path.read_bytes()
        digest = hashlib.sha256(content).hexdigest()
        if provenance is not None:
            expected = next(item for item in provenance['files'] if item['split'] == split)
            if digest != expected['sha256']:
                raise ValueError(f'Cached metadata checksum mismatch: {path}')
        part = [json.loads(line) for line in content.decode('utf-8').splitlines() if line.strip()]
        sources.append({'split': split, 'url': url, 'sha256': digest, 'rows': len(part)})
        raw_rows.extend(dict(row, source_split=split) for row in part)
    provenance_path.write_text(json.dumps({'repository': 'cambridgeltl/visual-spatial-reasoning',
        'revision': REVISION, 'files': sources}, indent=2), encoding='utf-8')

    # Allocate all images globally first, so later subsets inherit the same splits.
    images = sorted({r['image'] for r in raw_rows})
    random.Random(args.seed).shuffle(images)
    train_end = int(0.70 * len(images))
    validation_end = train_end + int(0.15 * len(images))
    assignment = {image: ('train' if i < train_end else 'validation' if i < validation_end else 'test')
                  for i, image in enumerate(images)}
    seen, rows, candidates, original_splits = {}, [], [], defaultdict(set)
    duplicates = 0
    for raw_row in raw_rows:
        image = raw_row['image']
        statement = raw_row['caption'].strip()
        truth = raw_row['label']
        if truth not in (0, 1) or not re.fullmatch(r'\d{12}\.jpg', image):
            raise ValueError('Invalid truth label or image filename.')
        if urlparse(raw_row['image_link']).hostname != 'images.cocodataset.org':
            raise ValueError('Unexpected image host.')
        key = (image, statement.casefold())
        original_splits[image].add(raw_row['source_split'])
        if key in seen:
            if seen[key] != truth:
                raise ValueError(f'Conflicting labels for {key}')
            duplicates += 1
            continue
        seen[key] = truth
        example_id = hashlib.sha256((image + '\n' + statement).encode('utf-8')).hexdigest()[:20]
        row = {
            'example_id': example_id, 'image_id': image.removesuffix('.jpg'),
            'image_path': f'data/vsr/images/{image}', 'image_url': raw_row['image_link'],
            'statement': statement, 'relation': raw_row['relation'], 'truth_label': truth,
            'split': assignment[image], 'source_split': raw_row['source_split'],
            'reference_frame': raw_row.get('reference_frame'),
            'annotator_id': raw_row.get('annotator_id'),
            'vote_true_validator_id': raw_row.get('vote_true_validator_id'),
            'vote_false_validator_id': raw_row.get('vote_false_validator_id'),
        }
        rows.append(row)
        if row['relation'] in RELATIONS:
            match = re.fullmatch(r'(The .+?) is ' + re.escape(row['relation']) + r' (the .+?)\.', statement)
            if not match:
                raise ValueError('Directional parsing rule needs review: ' + statement)
            candidates.append(dict(row, subject=match[1], object=match[2],
                requires_reference_frame_review=row['relation'] in {'left of', 'right of'}))
    if len({r['example_id'] for r in rows}) != len(rows):
        raise ValueError('Example ID collision.')
    for subset in (rows, candidates):
        image_sets = [{r['image_id'] for r in subset if r['split'] == split}
                      for split in ('train', 'validation', 'test')]
        if any(image_sets[i] & image_sets[j] for i in range(3) for j in range(i)):
            raise ValueError('Image leakage across splits.')
    save_jsonl(processed / 'all.jsonl', rows)
    save_jsonl(processed / 'directional_candidates.jsonl', candidates)
    image_manifest(processed / 'all_images.csv', rows)
    image_manifest(processed / 'directional_images.csv', candidates)
    pilot = [r for r in candidates if r['split'] == 'train']
    random.Random(args.seed).shuffle(pilot)
    save_jsonl(processed / 'pilot_candidates.jsonl', pilot[:100])
    image_manifest(processed / 'pilot_images.csv', pilot[:100])
    summary = {
        'revision': REVISION, 'split_seed': args.seed,
        'split_method': '70/15/15 of shuffled unique images globally; inherited by subsets',
        'original_split_shared_images': sum(len(v) > 1 for v in original_splits.values()),
        'duplicate_statements_removed': duplicates,
        'all': describe(rows), 'directional_candidates': describe(candidates),
        'pilot_candidates': describe(pilot[:100]),
        'status': 'Metadata candidates only. No images downloaded; directional semantics require visual audit.',
    }
    (processed / 'summary.json').write_text(json.dumps(summary, indent=2), encoding='utf-8')
    print(json.dumps(summary, indent=2))


if __name__ == '__main__':
    main()
